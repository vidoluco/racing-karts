const DICTS = { it, en };

// A stored choice wins, then the browser's language; anything that is not Italian plays in English.
export function pickLang(stored, navLang = '') {
  if (LANGS.includes(stored)) return stored;
  return /^it\b/i.test(navLang) ? 'it' : 'en';
}

export function translator(lang) {
  const dict = DICTS[lang] || en;
  return (key, vars) => {
    const text = dict[key] ?? en[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (all, k) => (k in vars ? String(vars[k]) : all)) : text;
  };
}

// [number, suffix]: 1° in Italian, 1st in English.
export function ordinal(lang, n) {
  if (lang === 'it') return [String(n), '°'];
  const tens = n % 100, unit = n % 10;
  const suffix = tens >= 11 && tens <= 13 ? 'th' : unit === 1 ? 'st' : unit === 2 ? 'nd' : unit === 3 ? 'rd' : 'th';
  return [String(n), suffix];
}
